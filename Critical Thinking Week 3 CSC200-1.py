# Weekly salaries of six employees
salaries = [500, 300, 700, 400, 600, 550]

# Sorting in ascending order
salaries_ascending = sorted(salaries)

# Sorting in descending order
salaries_descending = sorted(salaries, reverse=True)

# Printing the results
print("Salaries in Ascending Order:", salaries_ascending)
print("Salaries in Descending Order:", salaries_descending)